-- 远程函数的入参契约（JSON Schema）
--
-- 在此之前，「这个函数收什么参数」这件事只存在于三个地方：脚本作者的脑子里、
-- 脚本第一段那串 if 判断里、以及接入方翻聊天记录翻出来的一段示例 JSON。
-- 三者没有任何一处是机器可读的，于是：
--
--   1. 接入方少传一个字段，脚本在第三行抛 TypeError，调用方拿到的是 50290
--      「应用函数执行失败」—— 一个既不说少了什么、也不说是自己传错了的错误；
--   2. 控制台的试跑输入框是一个纯文本域，没有补全、没有校验；
--   3. 编辑器里 ctx.input 的类型只能是 any，写错字段名要到运行时才发现。
--
-- 有了这一列，同一份声明同时驱动：调用入口的前置校验（错误里逐条列出哪里不对）、
-- 试跑输入框的补全与校验、以及编辑器里 ctx.input 的真实类型。
--
-- 默认 '{}' 表示「不约束」，与加这一列之前的行为完全一致 —— 升级本身不改变任何行为。
ALTER TABLE app_functions
    ADD COLUMN IF NOT EXISTS input_schema JSONB NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN app_functions.input_schema IS
    '入参 JSON Schema；{} 表示不约束。同时驱动调用校验、试跑补全与编辑器类型';
